"""Core generator: OpenAPI 3.x spec -> pytest smoke suite source.

Smoke semantics: an endpoint passes when it answers with any status < 500
(401/403/404 are acceptable — the server responded, nothing crashed).
"""

from __future__ import annotations

import json
import re
import urllib.request
from pathlib import Path
from typing import Any

SMOKE_METHODS = ("get", "head")
_PARAM_RE = re.compile(r"\{([^}]+)\}")


def load_spec(src: str) -> dict[str, Any]:
    """Load a spec from a local path or an http(s) URL."""
    if src.startswith(("http://", "https://")):
        req = urllib.request.Request(src, headers={"User-Agent": "openapi-smoke-forge/1.0"})
        with urllib.request.urlopen(req, timeout=30) as resp:
            text = resp.read().decode("utf-8")
    else:
        text = Path(src).read_text(encoding="utf-8")
    spec = json.loads(text)
    if not isinstance(spec, dict) or not isinstance(spec.get("paths"), dict):
        raise TypeError("not an OpenAPI spec: missing 'paths' object")
    return spec


def sample_value(param: dict[str, Any]) -> str:
    """Best-effort concrete value for a path parameter."""
    if "example" in param:
        return str(param["example"])
    schema = param.get("schema") or {}
    if "enum" in schema:
        return str(schema["enum"][0])
    if "default" in schema:
        return str(schema["default"])
    return {
        "integer": "1",
        "number": "1.0",
        "boolean": "true",
    }.get(schema.get("type", ""), "1")


def operations(spec: dict[str, Any]) -> list[tuple[str, str, dict[str, Any]]]:
    """Yield (method, path, operation) for smokeable operations."""
    out = []
    for path, item in sorted(spec["paths"].items()):
        if not isinstance(item, dict):
            continue
        for method in SMOKE_METHODS:
            op = item.get(method)
            if isinstance(op, dict):
                out.append((method, path, op))
    return out


def _slug(method: str, path: str) -> str:
    return re.sub(r"[^a-zA-Z0-9]+", "_", f"{method}_{path}").strip("_").lower()


def fill_path(path: str, item: dict[str, Any], op: dict[str, Any]) -> str:
    params = {p["name"]: p for p in (item.get("parameters", []) + op.get("parameters", [])) if "name" in p}
    return _PARAM_RE.sub(lambda m: sample_value(params.get(m.group(1), {})), path)


def generate_tests(spec: dict[str, Any], base_url: str) -> str:
    """Generate pytest source covering every smokeable operation."""
    base_url = base_url.rstrip("/")
    lines = [
        '"""Generated by openapi-smoke-forge — one smoke test per GET/HEAD operation."""',
        "import urllib.error",
        "import urllib.request",
        "",
        f"BASE_URL = {json.dumps(base_url)}",
        "",
        "",
        "def _smoke(path):",
        "    req = urllib.request.Request(BASE_URL + path, headers={'User-Agent': 'openapi-smoke-forge/1.0'})",
        "    try:",
        "        with urllib.request.urlopen(req, timeout=30) as resp:",
        "            return resp.status",
        "    except urllib.error.HTTPError as exc:",
        "        return exc.code",
        "",
    ]
    seen: set[str] = set()
    count = 0
    for method, path, op in operations(spec):
        name = f"test_{_slug(method, path)}"
        if name in seen:
            continue
        seen.add(name)
        filled = fill_path(path, spec["paths"][path], op)
        label = f"{method.upper()} {path}"
        lines += [
            "",
            f"def {name}():",
            f"    # smoke: server must answer below 500 for {label}",
            f"    status = _smoke({json.dumps(filled)})",
            f'    assert status < 500, {json.dumps(label + " -> HTTP ")} + str(status)',
        ]
        count += 1
    lines.append("")
    header = f"# {count} smoke tests generated\n"
    return header + "\n".join(lines)


def write_suite(outdir: str, source: str, filename: str = "test_generated_smoke.py") -> Path:
    out = Path(outdir)
    out.mkdir(parents=True, exist_ok=True)
    target = out / filename
    target.write_text(source, encoding="utf-8")
    return target
